function makeTrain(service) {
  const [
    order,
    date,
    number,
    trainType,
    origin,
    originCode,
    departure,
    destination,
    destinationCode,
    arrival,
    lineNames,
    color,
  ] = service;
  return makeLoopTrain({
    order,
    id: `new_year_grand_loop_${date.replaceAll("-", "")}_${order}`,
    date,
    number,
    trainType,
    origin,
    originCode,
    departure,
    destination,
    destinationCode,
    arrival,
    lineNames,
    color,
    operator: OPERATOR,
    details: SERVICE_DETAILS[order] || {},
  });
}

